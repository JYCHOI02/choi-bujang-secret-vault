-- 2단계: 자료를 코드 밖으로 옮깁니다
-- Supabase Table 및 RLS 설정, 가상 메모 세 건 이전

-- 1. notes 테이블 생성 (owner_id는 uuid 형식이며 auth.users 외래키는 연결하지 않음)
create table if not exists notes (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  owner_id uuid,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 2. RLS (Row Level Security) 활성화
alter table notes enable row level security;

-- 3. anon 및 authenticated 역할에 자료 읽기(SELECT) 권한을 부여하지 않음
revoke select on table notes from anon, authenticated;

-- 4. 3단계 UUID 키 지원: 기존 bigint id 컬럼을 text로 변환 (Supabase SQL Editor에서 실행)
-- alter table notes alter column id drop identity if exists;
-- alter table notes alter column id type text;

-- 8단계: 메모(notes)와 다른 자원인 "강사 공지"를 별도 테이블·경로로 분리
-- (/api/announcements). 소유자가 없는 공용 읽기 자료이며, 서버는 route로
-- notes와 announcements를 구별합니다. 실습용 가상 내용만 넣습니다.
create table if not exists announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

alter table announcements enable row level security;
revoke select on table announcements from anon, authenticated;

insert into announcements (title, content) values
  ('[실습용 가상] 8단계 안내', '[실습용 가상] 메모와 강사 공지는 서로 다른 자원입니다.');

-- 10단계: 백업에서 자료실을 되살립니다. 침해 전에 확인한 메모 사본(notes_backup)과
-- 복원 시도 감사 기록(restore_audit)을 별도 테이블로 둡니다. 둘 다 서버 전용 키로만
-- 접근하며 공개 읽기 API를 두지 않습니다. content_sha256은 사본의 제목·내용이
-- 백업 시점 그대로인지 복원 전에 대조하는 지문입니다.
create table if not exists notes_backup (
  note_id text primary key,
  owner_id uuid not null,
  title text not null,
  content text not null,
  content_sha256 text not null,
  captured_at timestamptz default timezone('utc'::text, now()) not null
);

alter table notes_backup enable row level security;
revoke select on table notes_backup from anon, authenticated;

-- 복원 시도는 성공·중단 모두 한 줄씩 추가만 합니다. 기존 줄은 수정·삭제하지 않으므로
-- 다른 메모의 복원 이력도 그대로 보존됩니다.
create table if not exists restore_audit (
  id bigint generated by default as identity primary key,
  note_id text not null,
  action text not null,
  reason text,
  at timestamptz default timezone('utc'::text, now()) not null
);

alter table restore_audit enable row level security;
revoke select on table restore_audit from anon, authenticated;
